package com.soksak.soksak.credit;

/**
 * 마디가 움직인 이유. 원장 한 줄이 "왜 줄었는지"를 답할 수 있게 하는 유일한 근거다.
 * <p>
 * ⚠️ {@code @Enumerated(EnumType.STRING)}으로 저장한다 — ordinal로 저장하면 나중에 값을
 * 중간에 끼워 넣는 순간 <b>과거 행의 의미가 통째로 바뀐다.</b> 회계 기록에서는 치명적이다.
 * <p>
 * 요약(`/summarize`)은 일부러 없다. 사용자가 유발한 호출이 아니라서 물리면 "아무것도 안 했는데
 * 줄었다"가 되기 때문 — 정량제 단계에서는 무료로 둔다.
 */
public enum CreditReason {
    /** 메시지 전송 1건. */
    MESSAGE,
    /** 재생성 1건 — LLM 호출이 온전히 한 번 더 나가므로 전송과 같이 받는다. */
    REGENERATE,
    /**
     * 답이 끝내 안 나와서 돌려준 것. 차감 줄을 지우지 않고 <b>반대 부호의 줄을 하나 더</b> 쌓는다 —
     * 회계에서 기록을 고쳐 쓰면 "원래 얼마였나"를 잃는다.
     * <p>
     * ⚠️ 사용자가 중간에 나간 경우는 여기 해당하지 않는다. 생성과 저장이 끝까지 가서 답이 방에
     * 남기 때문이다({@code MessageService.sendToken}).
     */
    REFUND,
    /** 가입 보너스. */
    SIGNUP_BONUS,
    /**
     * 충전 화면에서 묶음을 고른 것. <b>결제 없이 바로 지급된다</b> — 결제 연동을 안 하기로 한
     * 이상 "원래는 여기서 결제로 넘어간다"는 자리를 비워 둔 모양이다([[todos]] A9).
     * <p>
     * {@code MANUAL_GRANT}(관리자 SQL)와 구분해 둔다. 나중에 결제를 붙이면 이 줄들이
     * "돈을 안 받고 준 것"으로 남아야 회계를 다시 맞출 수 있다.
     */
    TOPUP,
    /** 관리자가 직접 넣어준 것(SQL). 충전 API·쿠폰은 만들지 않는다. */
    MANUAL_GRANT,
}
